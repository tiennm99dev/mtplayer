# Regenerates packages/cargo-licenses.md from Cargo.lock: every third-party crate compiled into
# mtp.exe and pin-update.exe on Windows x64. Dev-dependencies and build scripts' own
# dependencies are left out, because they don't end up in a binary.
#
# Run it from any folder with PowerShell 7: pwsh packages/cargo-licenses.ps1

$ErrorActionPreference = 'Stop'

$root = Split-Path $PSScriptRoot -Parent
$json = cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc `
    --manifest-path (Join-Path $root 'Cargo.toml')
if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
$metadata = ($json -join "`n") | ConvertFrom-Json -Depth 64

$packages = @{}
foreach ($package in $metadata.packages) { $packages[$package.id] = $package }
$nodes = @{}
foreach ($node in $metadata.resolve.nodes) { $nodes[$node.id] = $node }

$queue = [System.Collections.Generic.Queue[string]]::new()
foreach ($package in $metadata.packages) {
    if ($package.targets | Where-Object { $_.kind -contains 'bin' }) {
        if ($null -eq $package.source) { $queue.Enqueue($package.id) }
    }
}

$seen = @{}
while ($queue.Count -gt 0) {
    $id = $queue.Dequeue()
    if ($seen.ContainsKey($id)) { continue }
    $seen[$id] = $true
    foreach ($dep in $nodes[$id].deps) {
        if ($dep.dep_kinds | Where-Object { $null -eq $_.kind }) { $queue.Enqueue($dep.pkg) }
    }
}

$rows = $seen.Keys |
    ForEach-Object { $packages[$_] } |
    Where-Object { $null -ne $_.source } |
    Sort-Object name, version

$lines = @(
    '# Rust crates compiled into MTPlayer'
    ''
    'This file is generated by `packages/cargo-licenses.ps1` from `Cargo.lock`. Do not edit it by'
    'hand. It lists every third-party crate compiled into `mtp.exe` and `pin-update.exe` on'
    'Windows x64.'
    ''
    '| Crate | Version | License |'
    '| --- | --- | --- |'
)
foreach ($row in $rows) { $lines += "| $($row.name) | $($row.version) | $($row.license) |" }

$text = ($lines -join "`n") + "`n"
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot 'cargo-licenses.md'), $text)
